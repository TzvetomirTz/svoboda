// Android: keep every byte of app data out of Google Drive backups and device-to-device transfers.
// `allowBackup: false` (app.json) only turns off cloud backup on Android 12+; device-to-device
// transfer still runs and follows the data extraction rules, so those exclude every domain too.
// Replaces the rules expo-secure-store would add (its plugin has configureAndroidBackup: false).
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const BACKUP_RULES = 'svoboda_backup_rules';
const EXTRACTION_RULES = 'svoboda_data_extraction_rules';

const DOMAINS = [
  'root',
  'file',
  'database',
  'sharedpref',
  'external',
  'device_root',
  'device_file',
  'device_database',
  'device_sharedpref',
];

const excludeAll = (indent) =>
  DOMAINS.map((domain) => `${indent}<exclude domain="${domain}" path="."/>`).join('\n');

// Android 11 and lower.
const BACKUP_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-no-android-backup.js: back up nothing. -->
<full-backup-content>
${excludeAll('  ')}
</full-backup-content>
`;

// Android 12 and higher.
const EXTRACTION_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-no-android-backup.js: back up and transfer nothing. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll('    ')}
  </cloud-backup>
  <device-transfer>
${excludeAll('    ')}
  </device-transfer>
</data-extraction-rules>
`;

module.exports = function withNoAndroidBackup(config) {
  config = withDangerousMod(config, [
    'android',
    (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${BACKUP_RULES}.xml`), BACKUP_XML);
      fs.writeFileSync(path.join(dir, `${EXTRACTION_RULES}.xml`), EXTRACTION_XML);
      return config;
    },
  ]);

  return withAndroidManifest(config, (config) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    application.$['android:allowBackup'] = 'false';
    application.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    application.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return config;
  });
};
