import ExpoModulesCore
import UIKit
import UniformTypeIdentifiers

// iOS side of Svoboda's privacy hardening. None of this protects against a compromised phone:
// the OS still draws the screen and delivers every touch.
public final class SvobodaSecureModule: Module {
  private var cover: UIView?
  private var coverEnabled = false

  public func definition() -> ModuleDefinition {
    Name("SvobodaSecure")

    // Copies text to this device only (no Universal Clipboard to other devices), and lets the
    // system clear it after `expiresIn` seconds.
    AsyncFunction("setSensitiveString") { (text: String, expiresIn: Double) in
      UIPasteboard.general.setItems(
        [[UTType.utf8PlainText.identifier: text]],
        options: [
          .localOnly: true,
          .expirationDate: Date().addingTimeInterval(expiresIn),
        ]
      )
    }.runOnQueue(.main)

    // Android only: touches from React Native are filtered at the window there.
    AsyncFunction("filterObscuredTouches") {}

    // Covers the app with the launch screen (white, or black in dark mode, with the centred
    // "Svoboda." wordmark) as soon as it stops being active, so the app switcher never shows a
    // message. The cover goes when the app is active again.
    AsyncFunction("enableBackgroundCover") {
      guard !self.coverEnabled else { return }
      self.coverEnabled = true
      NotificationCenter.default.addObserver(
        self, selector: #selector(self.showCover), name: UIApplication.willResignActiveNotification, object: nil)
      NotificationCenter.default.addObserver(
        self, selector: #selector(self.hideCover), name: UIApplication.didBecomeActiveNotification, object: nil)
    }.runOnQueue(.main)

    OnDestroy {
      NotificationCenter.default.removeObserver(self)
      DispatchQueue.main.async { self.hideCover() }
    }

    // On iOS the container has nothing to add: there is no tapjacking overlay API and no
    // accessibility-sensitive flag to set.
    View(SecureInputView.self) {}
  }

  private var keyWindow: UIWindow? {
    UIApplication.shared.connectedScenes
      .compactMap { $0 as? UIWindowScene }
      .flatMap { $0.windows }
      .first { $0.isKeyWindow }
  }

  @objc
  private func showCover() {
    guard cover == nil, let window = keyWindow else { return }
    let view = Self.launchScreenView() ?? {
      let plain = UIView()
      plain.backgroundColor = .systemBackground
      return plain
    }()
    view.frame = window.bounds
    view.autoresizingMask = [.flexibleWidth, .flexibleHeight]
    window.addSubview(view)
    cover = view
  }

  @objc
  private func hideCover() {
    cover?.removeFromSuperview()
    cover = nil
  }

  // The same storyboard the app launches with, generated by expo-splash-screen.
  private static func launchScreenView() -> UIView? {
    guard Bundle.main.path(forResource: "SplashScreen", ofType: "storyboardc") != nil else { return nil }
    return UIStoryboard(name: "SplashScreen", bundle: .main).instantiateInitialViewController()?.view
  }
}

public final class SecureInputView: ExpoView {}
